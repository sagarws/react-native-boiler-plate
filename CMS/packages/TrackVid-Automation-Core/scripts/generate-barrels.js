#!/usr/bin/env node
/**
 * Regenerates every index.js barrel in the package. Run after adding, renaming or
 * removing a file — `npm run barrels`.
 *
 * Each barrel is a plain object of lazy getters over *literal* require strings:
 *
 *   module.exports = {
 *     get db() { return require("./db"); },
 *     get platforms() { return require("./platforms"); },
 *   };
 *
 * Literal strings so Rollup/esbuild can follow them when a consumer bundles the
 * package (Trackvid-CMS bundles its Electron main process); getters so requiring
 * the root does not eagerly pull mongodb and every platform flow into memory.
 *
 * Directory names are camelCased: claim-management -> claimManagement.
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
// "logs" is a RUNTIME artifact, not source: the server writes error logs into
// packages/TrackVid-Automation-Core/logs, it is gitignored, and walking it put a
// bogus `logs` export into the root barrel (and a generated index.js inside the
// log directory) on any machine that had ever run a job.
// "Error_Case" is DOCUMENTATION — write-ups of failures that were expensive to
// diagnose. Walking it exported an `ErrorCase` namespace from the package root
// and wrote an index.js into a directory of .txt files, which is a public API
// nobody asked for over something that is not code.
// "tests" is the package's own test suite (`npm test` → node --test). Walking it
// exported a `tests` namespace from the package root and wrote an index.js into
// it — a public API made out of the checks on the API.
const SKIP = new Set(["node_modules", "scripts", "types", "coverage", "logs", "Error_Case", "tests"]);

const toKey = (name) => name.replace(/[-_.](\w)/g, (_, c) => c.toUpperCase());

function entriesOf(dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const { name } = e;
    if (name.startsWith(".") || SKIP.has(name) || name === "index.js") continue;
    if (e.isDirectory()) out.push({ key: toKey(name), spec: `./${name}` });
    else if (name.endsWith(".js") && !name.endsWith(".test.js")) out.push({ key: toKey(name.slice(0, -3)), spec: `./${name.slice(0, -3)}` });
  }
  return out;
}

let written = 0;

(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.isDirectory() && !e.name.startsWith(".") && !SKIP.has(e.name)) walk(path.join(dir, e.name));
  }

  const entries = entriesOf(dir);
  const rel = path.relative(ROOT, dir) || "the package root";
  const body = entries.length
    ? entries.map((e) => `\tget ${e.key}() {\n\t\treturn require("${e.spec}");\n\t},`).join("\n")
    : "\t// nothing here yet — drop a file in and run `npm run barrels`";

  fs.writeFileSync(
    path.join(dir, "index.js"),
    `// GENERATED by scripts/generate-barrels.js — do not edit by hand.\n` +
      `// Barrel for ${rel}. Run \`npm run barrels\` after adding or removing a file.\n\n` +
      `module.exports = {\n${body}\n};\n`
  );
  written++;
})(ROOT);

console.log(`barrels: wrote ${written} index.js files`);
