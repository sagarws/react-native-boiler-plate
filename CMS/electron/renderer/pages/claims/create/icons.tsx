import { Box, type BoxProps } from '@mui/material'

/*
 * FOR scripts/build-icon-subset.cjs, which finds icons by scanning for literal
 * `tabler-…` tokens. This shim builds each class name at runtime, so its glyphs
 * were never found and ten of them rendered as nothing (the empty tiles on the
 * bulk-claim dialogs). Listed here so `npm run icons` keeps them:
 *
 *  tabler-arrow-left tabler-camera tabler-circle-check tabler-circle-filled
 *  tabler-cloud-upload tabler-download tabler-eye tabler-file
 *  tabler-file-spreadsheet tabler-file-type-pdf tabler-grip-vertical
 *  tabler-help-circle tabler-info-circle tabler-list-check tabler-pencil
 *  tabler-photo tabler-photo-plus tabler-player-pause tabler-player-play
 *  tabler-player-stop tabler-refresh tabler-trash tabler-video
 *  tabler-video-off tabler-x
 */

/**
 * The icons the ported form asks for, drawn from the set this app ships.
 *
 * `@mui/icons-material` is not a dependency here and will not become one: the
 * app has ONE icon set — Tabler, bundled as a generated subset — and a second
 * one would be a 2.8MB font's worth of a decision already made. But the ported
 * form imports its icons by MUI's names, in twenty files, and rewriting each
 * call site is a permanent diff against the page this one has to stay
 * comparable to.
 *
 * So the names are kept and the drawings are ours. Each export below is the
 * MUI icon's name rendering the nearest Tabler glyph, accepting the props MUI
 * icons accept — `sx`, `fontSize`, `className`, `onClick` — so a call site
 * reads unchanged.
 *
 * AFTER ADDING ONE HERE, RUN `npm run icons`. The subset is generated by
 * scanning the renderer for `tabler-*` class names; a glyph that is not in it
 * renders as nothing at all, with no error anywhere.
 */

type Size = 'inherit' | 'small' | 'medium' | 'large'

export interface IconProps extends Omit<BoxProps, 'component'> {
  fontSize?: Size
}

/** MUI's four sizes, in pixels, so a ported `fontSize="small"` still means small. */
const SIZE: Record<Size, string> = {
  inherit: 'inherit',
  small: '1.25rem',
  medium: '1.5rem',
  large: '2.1875rem'
}

const icon = (glyph: string) => {
  const Icon = ({ fontSize = 'medium', sx, className, ...rest }: IconProps) => (
    <Box
      component='i'
      aria-hidden='true'
      className={className ? `tabler-${glyph} ${className}` : `tabler-${glyph}`}
      sx={{ fontSize: SIZE[fontSize], lineHeight: 1, display: 'inline-flex', ...sx }}
      {...rest}
    />
  )

  Icon.displayName = `Tabler(${glyph})`

  return Icon
}

