/** 10-band EQ presets (31 Hz … 16 kHz). Boosts come with a lower preamp. */
const eq = (
  id: string,
  name: string,
  bands: number[],
  preamp: number,
  extra: Partial<EqProfile> = {},
): EqProfile => ({
  id,
  name,
  builtIn: true,
  preamp,
  eq: bands,
  bass: 0,
  treble: 0,
  vocal: 0,
  ...extra,
});

