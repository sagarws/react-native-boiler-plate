#!/usr/bin/env node
/** Regenerates every generated controller in place from its legacy route file (after a pin bump). */
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const BE = path.resolve(__dirname, '..');
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : e.name.endsWith('.controller.ts') ? [path.join(d, e.name)] : []));
let bad = 0;
for (const file of walk(path.join(BE, 'src/modules'))) {
  const src = fs.readFileSync(file, 'utf8');
  const m = /GENERATED by scripts\/gen-nest-controller\.js from (\S+) —/.exec(src);
  if (!m) continue;
  const ctrlPath = /@Controller\((?:'([^']*)')?\)/.exec(src)[1] ?? '';
  const cls = /export class (\w+)Controller/.exec(src)[1];
  const r = spawnSync('node', [path.join(__dirname, 'gen-nest-controller.js'), m[1], `/${ctrlPath}`, cls, file], { cwd: BE, encoding: 'utf8' });
  let out = fs.readFileSync(file, 'utf8');
  if (path.relative(path.join(BE, 'src/modules'), file).startsWith('platforms' + path.sep)) out = out.replace(/'\.\.\/\.\.\/core\//g, "'../../../core/");
  if (!ctrlPath) out = out.replace("@Controller('')", '@Controller()');
  fs.writeFileSync(file, out);
  console.log(`${path.relative(BE, file)}: ${r.stderr.trim()}`);
  if (r.status === 2) bad++;
}
process.exit(bad ? 2 : 0);
