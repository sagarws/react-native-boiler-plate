import fs from 'fs';
import os from 'os';
import path from 'path';
import { spawnSync } from 'child_process';

/**
 * Generated controllers must match what the generator produces from the CURRENT legacy route
 * files. After a submodule pin bump this fails for every route file that changed in legacy
 * (new routes, changed middleware chains, edited inline helpers) → regenerate + re-test.
 */
const BE = path.resolve(__dirname, '..', '..');
const walk = (d: string): string[] => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : e.name.endsWith('.controller.ts') ? [path.join(d, e.name)] : []));
const generated = walk(path.join(BE, 'src/modules')).filter((f) => fs.readFileSync(f, 'utf8').includes('GENERATED by scripts/gen-nest-controller.js'));

describe('generated controllers are up to date with legacy route files', () => {
  it('found generated controllers', () => expect(generated.length).toBeGreaterThan(15));

  it.each(generated.map((f) => [path.relative(BE, f), f]))('%s', (_rel, file) => {
    const src = fs.readFileSync(file, 'utf8');
    const legacyFile = /GENERATED by scripts\/gen-nest-controller\.js from (\S+) —/.exec(src)[1];
    const ctrlPath = /@Controller\((?:'([^']*)')?\)/.exec(src)[1] ?? '';
    const cls = /export class (\w+)Controller/.exec(src)[1];
    const tmp = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'gen-')), 'out.ts');
    const r = spawnSync('node', [path.join(BE, 'scripts/gen-nest-controller.js'), legacyFile, `/${ctrlPath}`, cls, tmp], { cwd: BE, encoding: 'utf8' });
    expect(r.status === 0 || r.status === 2).toBe(true);
    let fresh = fs.readFileSync(tmp, 'utf8');
    // platform controllers live one directory deeper (relative core imports adjusted after generation)
    if (src.includes("'../../../core/")) fresh = fresh.replace(/'\.\.\/\.\.\/core\//g, "'../../../core/");
    if (!ctrlPath) fresh = fresh.replace("@Controller('')", '@Controller()');
    expect(src).toBe(fresh);
  });
});
